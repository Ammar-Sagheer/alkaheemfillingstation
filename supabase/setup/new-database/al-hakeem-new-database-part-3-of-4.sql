-- ---------------------------------------------------------------------------
-- 6. A replaced nozzle's wiring is history, and history does not get rewired.
--
-- set_nozzle_wiring() (022) updates tank_id, which decides WHICH TANK every
-- one of that nozzle's past sales was drawn out of. Pointing a retired diesel
-- nozzle at the petrol tank would silently move months of litres from one tank
-- to the other and make both tanks' gain/loss fiction. It was safe while every
-- nozzle was live; it is not now.
-- ---------------------------------------------------------------------------
create or replace function public.set_nozzle_wiring(p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
  v_dead  text;
begin
  if not public.is_super_admin() then
    raise exception 'Only the owner may change the nozzle wiring' using errcode = '42501';
  end if;

  select string_agg('Unit ' || n.unit_number || ' · Nozzle ' || n.nozzle_label, ', '
                    order by n.unit_number, n.nozzle_label)
    into v_dead
    from jsonb_array_elements(p_rows) as row_data
    join public.nozzles n on n.id = (row_data ->> 'nozzle_id')::uuid
   where n.retired_on is not null;

  if v_dead is not null then
    raise exception
      'A replaced nozzle''s wiring cannot be changed (%). Its readings are already in the books '
      'and the tank they came out of has to stay as it was.', v_dead
      using errcode = '23514';
  end if;

  update public.nozzles n
     set tank_id          = (row_data->>'tank_id')::uuid,
         starting_reading = (row_data->>'starting_reading')::numeric
    from jsonb_array_elements(p_rows) as row_data
   where n.id = (row_data->>'nozzle_id')::uuid;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke execute on function public.set_nozzle_wiring(jsonb) from public, anon;
grant  execute on function public.set_nozzle_wiring(jsonb) to authenticated;

-- ===================================================================== 057_replaced_units_in_the_activity_log.sql
-- =============================================================================
-- 057_replaced_units_in_the_activity_log.sql
--
-- The audit trail has logged nozzle rows since 035, but its one-line summary
-- for them was "Unit 1 · Nozzle A" and nothing else - which is exactly the
-- wrong amount of detail for the event 056 introduced. Replacing a unit writes
-- four lines into the log (two nozzles retired, two fitted), and all four read
-- identically apart from the label. The owner opening the log to ask "when did
-- we change the diesel pump?" would find four lines that do not say.
--
-- So the summary now carries the service window: "fitted 14 Aug 2026" on the
-- new pair, "replaced 14 Aug 2026" on the old. Nothing else about the log
-- changes.
--
-- WHY THE WHOLE FUNCTION IS HERE AGAIN. `trg_write_activity()` is one plpgsql
-- body with a case over every table; there is no way to patch one branch of it.
-- 048 reproduced it whole for the same reason, and this is that same function
-- with only the `when 'nozzles'` branch altered.
-- =============================================================================

create or replace function public.trg_write_activity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_new       jsonb;
  v_old       jsonb;
  v_row       jsonb;
  v_action    text;
  v_label     text;
  v_summary   text;
  v_date      date;
  v_amount    numeric;
  v_changes   jsonb;
  v_actor_id  uuid;
  v_actor     text;
  v_details   jsonb;
  -- Columns recomputed by other triggers, or noise. A change to these alone is
  -- not somebody doing something, so the write goes unlogged.
  v_ignored text[] := array[
    'current_stock_litres', 'created_at', 'credit_sale_id', 'lubricant_sale_id',
    'expected_stock', 'gain_loss'
  ];
begin
  v_new := case when tg_op = 'DELETE' then null else to_jsonb(new) end;
  v_old := case when tg_op = 'INSERT' then null else to_jsonb(old) end;
  v_row := coalesce(v_new, v_old);

  v_action := case tg_op when 'INSERT' then 'created'
                         when 'UPDATE' then 'changed'
                         else 'deleted' end;

  if tg_op = 'UPDATE' then
    select coalesce(jsonb_agg(jsonb_build_object(
             'field', t.k, 'from', v_old -> t.k, 'to', v_new -> t.k
           ) order by t.k), '[]'::jsonb)
      into v_changes
      from jsonb_object_keys(v_new) as t(k)
     where not (t.k = any (v_ignored))
       and (v_old -> t.k) is distinct from (v_new -> t.k);

    if jsonb_array_length(v_changes) = 0 then
      return coalesce(new, old);
    end if;
  end if;

  if tg_table_name = 'ledger_entries'
     and (v_row ->> 'credit_sale_id' is not null or v_row ->> 'lubricant_sale_id' is not null)
  then
    return coalesce(new, old);
  end if;

  select a.actor_id, a.actor_name into v_actor_id, v_actor from public.activity_actor() a;

  case tg_table_name

    when 'nozzle_readings' then
      v_label := 'Reading';
      v_date := (v_row ->> 'reading_date')::date;
      v_amount := (v_row ->> 'sale_amount')::numeric;
      select 'Unit ' || n.unit_number || ' · Nozzle ' || n.nozzle_label
        into v_summary from public.nozzles n where n.id = (v_row ->> 'nozzle_id')::uuid;
      v_summary := coalesce(v_summary, 'A nozzle')
        || ' — ' || to_char((v_row ->> 'litres_sold')::numeric, 'FM999,999,990.00') || ' L'
        || ', Rs ' || to_char((v_row ->> 'sale_amount')::numeric, 'FM999,999,999,990');

    when 'credit_sales' then
      v_label := 'Credit slip';
      v_amount := (v_row ->> 'amount')::numeric;
      select c.name into v_summary from public.customers c where c.id = (v_row ->> 'customer_id')::uuid;
      v_summary := coalesce(v_summary, 'A customer')
        || ' — ' || to_char((v_row ->> 'litres')::numeric, 'FM999,999,990.00') || ' L'
        || ', Rs ' || to_char((v_row ->> 'amount')::numeric, 'FM999,999,999,990');

    when 'ledger_entries' then
      v_label := case v_row ->> 'entry_type' when 'credit' then 'Payment or credit'
                                             else 'Charge to a customer' end;
      v_date := (v_row ->> 'entry_date')::date;
      v_amount := (v_row ->> 'amount')::numeric;
      select c.name into v_summary from public.customers c where c.id = (v_row ->> 'customer_id')::uuid;
      v_summary := coalesce(v_summary, 'A customer')
        || ' — Rs ' || to_char((v_row ->> 'amount')::numeric, 'FM999,999,999,990')
        || coalesce(' · ' || nullif(v_row ->> 'note', ''), '');

    when 'lubricant_sales' then
      v_label := 'Oil sale';
      v_date := (v_row ->> 'sale_date')::date;
      v_amount := (v_row ->> 'amount')::numeric;
      select l.name into v_summary from public.lubricants l where l.id = (v_row ->> 'lubricant_id')::uuid;
      v_summary := coalesce(v_summary, 'A lubricant')
        || ' — ' || to_char((v_row ->> 'litres')::numeric, 'FM999,999,990.000') || ' L'
        || ', Rs ' || to_char((v_row ->> 'amount')::numeric, 'FM999,999,999,990');

    when 'lubricant_purchases' then
      v_label := 'Oil delivery';
      v_date := (v_row ->> 'purchase_date')::date;
      v_amount := (v_row ->> 'total_cost')::numeric;
      select l.name into v_summary from public.lubricants l where l.id = (v_row ->> 'lubricant_id')::uuid;
      v_summary := coalesce(v_summary, 'A lubricant')
        || ' — ' || to_char((v_row ->> 'quantity_litres')::numeric, 'FM999,999,990.00') || ' L'
        || coalesce(' from ' || nullif(v_row ->> 'supplier_name', ''), '')
        || ', Rs ' || to_char((v_row ->> 'total_cost')::numeric, 'FM999,999,999,990');

    when 'fuel_purchases' then
      v_label := 'Fuel delivery';
      v_date := (v_row ->> 'purchase_date')::date;
      v_amount := (v_row ->> 'total_cost')::numeric;
      select t.name into v_summary from public.tanks t where t.id = (v_row ->> 'tank_id')::uuid;
      v_summary := coalesce(v_summary, 'A tank')
        || ' — ' || to_char((v_row ->> 'quantity_litres')::numeric, 'FM999,999,990.00') || ' L'
        || coalesce(' from ' || nullif(v_row ->> 'supplier_name', ''), '')
        || ', Rs ' || to_char((v_row ->> 'total_cost')::numeric, 'FM999,999,999,990')
        || ' · ' || (v_row ->> 'payment_status');

    when 'stock_checks' then
      v_label := 'Tank dip';
      v_date := (v_row ->> 'books_date')::date;
      select t.name into v_summary from public.tanks t where t.id = (v_row ->> 'tank_id')::uuid;
      v_summary := coalesce(v_summary, 'A tank')
        || ' — dipped at ' || to_char((v_row ->> 'actual_dip_reading')::numeric, 'FM999,999,990.00') || ' L'
        || ', books said ' || to_char((v_row ->> 'expected_stock')::numeric, 'FM999,999,990.00') || ' L'
        || ' (measured ' || (v_row ->> 'taken') || ' of '
        || to_char((v_row ->> 'check_date')::date, 'FMDD Mon YYYY') || ')';

    when 'expenses' then
      v_label := 'Expense';
      v_date := (v_row ->> 'expense_date')::date;
      v_amount := (v_row ->> 'amount')::numeric;
      v_summary := coalesce(nullif(v_row ->> 'category', ''), 'Uncategorised')
        || ' — Rs ' || to_char((v_row ->> 'amount')::numeric, 'FM999,999,999,990')
        || coalesce(' · ' || nullif(v_row ->> 'note', ''), '');

    when 'bank_transactions' then
      v_label := case v_row ->> 'txn_type' when 'deposit' then 'Money into the bank'
                                           else 'Money out of the bank' end;
      v_date := (v_row ->> 'txn_date')::date;
      v_amount := (v_row ->> 'amount')::numeric;
      select b.bank_name || coalesce(' · ' || b.account_label, '') into v_summary
        from public.bank_accounts b where b.id = (v_row ->> 'account_id')::uuid;
      v_summary := coalesce(v_summary, 'An account')
        || ' — Rs ' || to_char((v_row ->> 'amount')::numeric, 'FM999,999,999,990')
        || coalesce(' · ' || nullif(v_row ->> 'category', ''), '');

    when 'bank_accounts' then
      v_label := 'Bank account';
      v_summary := coalesce(v_row ->> 'bank_name', 'An account')
        || coalesce(' · ' || nullif(v_row ->> 'account_label', ''), '');

    when 'customers' then
      v_label := 'Customer';
      v_summary := coalesce(nullif(v_row ->> 'name', ''), 'A customer')
        || coalesce(' · ' || nullif(v_row ->> 'vehicle_number', ''), '');

    when 'lubricants' then
      v_label := 'Lubricant';
      v_summary := coalesce(nullif(v_row ->> 'name', ''), 'A lubricant');

    when 'fuel_prices' then
      v_label := 'Fuel rate';
      v_summary := initcap(v_row ->> 'fuel_type')
        || ' — Rs ' || to_char((v_row ->> 'rate')::numeric, 'FM999,990.00') || ' / L'
        || ' from ' || to_char((v_row ->> 'effective_from')::date, 'DD Mon YYYY');

    when 'tanks' then
      v_label := 'Tank';
      v_summary := coalesce(nullif(v_row ->> 'name', ''), 'A tank')
        || ' · ' || coalesce(v_row ->> 'fuel_type', '');

    -- Changed in 057: a nozzle now has a service window, and the day a unit
    -- was swapped is the fact somebody comes to this log looking for.
    when 'nozzles' then
      v_label := 'Nozzle';
      v_summary := 'Unit ' || coalesce(v_row ->> 'unit_number', '?')
        || ' · Nozzle ' || coalesce(v_row ->> 'nozzle_label', '?')
        || coalesce(' · fitted '
             || to_char((v_row ->> 'commissioned_on')::date, 'FMDD Mon YYYY'), '')
        || coalesce(' · replaced '
             || to_char((v_row ->> 'retired_on')::date, 'FMDD Mon YYYY'), '');

    when 'profiles' then
      v_label := 'Login';
      v_summary := coalesce(nullif(v_row ->> 'full_name', ''), 'Someone')
        || ' · ' || coalesce(v_row ->> 'role', '')
        || case when (v_row ->> 'is_active')::boolean then '' else ' · deactivated' end;

    when 'company_assets' then
      v_label := 'Company asset';
      v_date := (v_row ->> 'purchase_date')::date;
      v_amount := (v_row ->> 'purchase_value')::numeric;
      v_summary := coalesce(nullif(v_row ->> 'name', ''), 'An asset')
        || ' — ' || initcap(coalesce(v_row ->> 'category', 'other'))
        || ', Rs ' || to_char((v_row ->> 'purchase_value')::numeric, 'FM999,999,999,990');

    -- New: cash into or out of the safe. The details line is the whole point
    -- of the entry - "Munir sb by Hamza saqib", "Zamzam code transfer 118014"
    -- - so it is carried into the log rather than left behind in the row.
    when 'treasury_entries' then
      v_label := case v_row ->> 'direction' when 'in' then 'Cash into the safe'
                                            else 'Cash out of the safe' end;
      v_date := (v_row ->> 'entry_date')::date;
      v_amount := (v_row ->> 'amount')::numeric;
      v_summary := 'Rs ' || to_char((v_row ->> 'amount')::numeric, 'FM999,999,999,990')
        || ' · ' || initcap(replace(coalesce(v_row ->> 'category', 'other'), '_', ' '))
        || coalesce(' — ' || nullif(btrim(coalesce(v_row ->> 'details', '')), ''), '');

    else
      v_label := tg_table_name;
      v_summary := tg_table_name;
  end case;

  v_details := jsonb_build_object('row', v_row)
             || case when v_changes is null then '{}'::jsonb
                     else jsonb_build_object('changes', v_changes) end;

  insert into public.activity_log
    (actor_id, actor_name, action, entity, entity_label, entity_id,
     summary, entry_date, amount, details)
  values
    (v_actor_id, v_actor, v_action, tg_table_name, v_label,
     (v_row ->> 'id')::uuid, v_summary, v_date, v_amount, v_details);

  return coalesce(new, old);

exception when others then
  return coalesce(new, old);
end;
$$;

-- ===================================================================== 058_rearranging_the_forecourt.sql
-- =============================================================================
-- 058_rearranging_the_forecourt.sql
--
-- The unit number and the nozzle label become editable, in Edit nozzle wiring.
--
-- WHY. 056 handles a pump being REPLACED - different hardware, meters starting
-- again, a date dividing before from after. It does not handle the other half
-- of what actually happened on 1 Sep 2026: the pumps were also RE-ARRANGED. The
-- petrol unit that stood at position 2 now stands at position 1, and the new
-- diesel unit stands at position 2. Nothing about that is a hardware event -
-- the petrol dispenser is the same object with the same meters, still counting
-- up from 48,760.78 - it is only called something else now.
--
-- That is a LABEL, and until now the labels were the one part of the forecourt
-- the owner could not change without a migration. `unit_number` and
-- `nozzle_label` are how he refers to a pump when he is standing in front of
-- it; if the app disagrees with the sticker on the machine, the app is wrong.
--
-- WHAT A RENAME MEANS, SAID PLAINLY. It applies to the WHOLE history. A reading
-- from 15 August will show under the pump's new number, because there is one
-- number per nozzle and this changes it. That is the right behaviour for a
-- rearrangement, where the owner's own mental map has moved with the hardware
-- and he will never again think of that pump as Unit 2. It is the WRONG tool
-- for a pump that was actually swapped out - use "Replace this unit" for that,
-- which keeps the old readings under the old pump and starts the new one
-- separately. The dialog says so.
--
-- ---------------------------------------------------------------------------
-- TWO THINGS THIS NEEDS FROM THE DATABASE, AND BOTH ARE THE INTERESTING PART.
--
-- 1. A STRAIGHT SWAP HAS TO BE LEGAL. Renumbering 2 -> 1 and 1 -> 2 is the
--    normal case, not an exotic one, and it passes through a moment where two
--    nozzles both claim position 1. A plain unique index checks per row as the
--    UPDATE walks the table, so it refuses the swap halfway through and there
--    is no ordering of the rows that avoids it. The constraint therefore has to
--    be DEFERRABLE - checked once, at the end, when the forecourt is whole
--    again. This is the same reason 044's treasury guard is a deferred
--    constraint trigger rather than a row check.
--
-- 2. A POSITION IS ONLY OCCUPIED FOR THE DAYS IT IS OCCUPIED. 056's index
--    (`nozzles_live_unit_label_idx`) said "one LIVE nozzle per unit and label",
--    which was enough while the only event was a replacement. It is not enough
--    now: the retired diesel pump still holds position 1 for every day up to 31
--    August, and the petrol pump moving into position 1 must not be allowed to
--    claim those same days as well - two pumps at one position on one date is
--    exactly the state that makes a day's sheet unreadable.
--
--    So the rule becomes an EXCLUSION CONSTRAINT over the service window 056
--    already gave every nozzle: no two nozzles may share a unit number and a
--    label over overlapping days. It is strictly stronger than the index it
--    replaces (which said nothing at all about the past), and it is what makes
--    the rearrangement safe to type in any order - retiring the diesel pump on
--    31 Aug and giving the petrol pump position 1 from 1 Sep do not overlap, so
--    neither has to happen first.
-- =============================================================================

-- `=` on smallint and text inside a GiST index, which a plain GiST cannot do.
create extension if not exists btree_gist;

-- ---------------------------------------------------------------------------
-- One pump per position per day.
--
-- daterange(commissioned_on, retired_on, '[]') is the days this nozzle was on
-- the forecourt. A NULL bound in a range constructor means UNBOUNDED, which is
-- exactly what a null commissioning date already means in 056 - "here from
-- before the app was" - so the two definitions agree without a coalesce.
-- ---------------------------------------------------------------------------
drop index if exists public.nozzles_live_unit_label_idx;

alter table public.nozzles drop constraint if exists nozzles_one_pump_per_position;
alter table public.nozzles
  add constraint nozzles_one_pump_per_position
  exclude using gist (
    unit_number  with =,
    nozzle_label with =,
    daterange(commissioned_on, retired_on, '[]') with &&
  )
  deferrable initially deferred;

comment on constraint nozzles_one_pump_per_position on public.nozzles is
  'No two nozzles share a unit number and label over overlapping days. Deferred, so a straight swap is one statement.';

-- A label is what someone reads off the machine; blank is not a label.
alter table public.nozzles drop constraint if exists nozzles_label_not_blank;
alter table public.nozzles
  add constraint nozzles_label_not_blank
  check (length(btrim(nozzle_label)) > 0);

-- ---------------------------------------------------------------------------
-- Saving the wiring, now including where each pump stands.
--
-- Rebuilt from 056, which was itself 022 plus the retired-nozzle guard. Two
-- changes:
--
--   * `unit_number` and `nozzle_label` are written from the form. They are the
--     only two fields a RETIRED nozzle will accept - see below.
--   * the deferred constraint is forced to check itself before this function
--     returns, so a clash comes back as a sentence about two pumps at one
--     position rather than as a raw 23P01 at COMMIT, from underneath the
--     Server Action, with the row numbers of a GiST index in it.
--
-- WHY A RETIRED NOZZLE MAY BE RENAMED BUT STILL NOT REWIRED. Its `tank_id`
-- decides which tank every one of its past sales was drawn out of, and its
-- `starting_reading` is a meter figure - both are load-bearing arithmetic, and
-- 056 froze them for that reason. Its unit number and label are neither: they
-- are the caption on rows that are already correct. Freezing those too would
-- leave the owner unable to renumber the pump that was replaced, and therefore
-- unable to move anything into the position it used to hold - which is the
-- whole job this migration exists for.
-- ---------------------------------------------------------------------------
create or replace function public.set_nozzle_wiring(p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
  v_dead  text;
begin
  if not public.is_super_admin() then
    raise exception 'Only the owner may change the nozzle wiring' using errcode = '42501';
  end if;

  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then
    raise exception 'Nothing to save.' using errcode = '23514';
  end if;

  -- A field that is PRESENT but empty is a mistake, not an instruction. The
  -- update below coalesces a missing key to "leave this alone", which is what
  -- lets a retired nozzle's row carry only its caption - but that same
  -- coalesce would quietly swallow a label someone had cleared and meant to
  -- clear. Silently keeping the old value is the worst of the three possible
  -- behaviours, so a blank that was sent on purpose is refused by name.
  if exists (
    select 1 from jsonb_array_elements(p_rows) r
     where r ? 'nozzle_label' and btrim(coalesce(r ->> 'nozzle_label', '')) = ''
  ) then
    raise exception 'Every nozzle needs a label - it is what is written on the machine.'
      using errcode = '23514';
  end if;

  if exists (
    select 1 from jsonb_array_elements(p_rows) r
     where r ? 'unit_number'
       and coalesce(nullif(r ->> 'unit_number', '')::int, 1) < 1
  ) then
    raise exception 'A unit number has to be a whole number above zero.' using errcode = '23514';
  end if;

  -- A replaced nozzle keeps the tank it drew from and the meter it started on.
  select string_agg('Unit ' || n.unit_number || ' · Nozzle ' || n.nozzle_label, ', '
                    order by n.unit_number, n.nozzle_label)
    into v_dead
    from jsonb_array_elements(p_rows) as row_data
    join public.nozzles n on n.id = (row_data ->> 'nozzle_id')::uuid
   where n.retired_on is not null
     and (
       (row_data ? 'tank_id'
         and nullif(row_data ->> 'tank_id', '') is not null
         and (row_data ->> 'tank_id')::uuid is distinct from n.tank_id)
       or
       (row_data ? 'starting_reading'
         and nullif(row_data ->> 'starting_reading', '') is not null
         and (row_data ->> 'starting_reading')::numeric is distinct from n.starting_reading)
     );

