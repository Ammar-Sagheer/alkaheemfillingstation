--      `starting_reading` set to each meter's 31 August closing (A 48,760.78,
--      B 24,835.72) rather than 0. The meter did not go back to zero; only the
--      fuel behind it changed, and a starting reading of 0 would count the
--      pump's whole life as the first day's sales the moment a September
--      reading was entered (012).
--
--   4. `replaced_by` links each old row to its new one, so Settings reads as
--      one pump with a history rather than four unrelated rows.
--
-- WHAT THIS DOES NOT TOUCH. No reading, no rupee, no ledger entry, no dip. The
-- money was never wrong - `rate_per_litre` and `sale_amount` live on each
-- reading - and the September dips taken on 1 Sep are the baseline every
-- current stock figure is measured from, so today's tank figures do not move
-- either. What moves is which tank August's litres are counted against, back to
-- what it was before 2 September.
--
-- SAFE TO RUN TWICE. If Unit 1's petrol nozzles are already retired the whole
-- thing is a no-op, and it refuses outright rather than guessing if the pump is
-- not in the state described above.
-- =============================================================================

do $$
declare
  v_petrol   uuid;
  v_diesel   uuid;
  v_old_a    uuid := '7c4bd261-a5a8-4f0b-b5eb-dcf24a86d6ae';  -- traded all Aug as Unit 2 · A
  v_old_b    uuid := '078e541c-6f53-430a-9047-72ad12a5e24f';  -- traded all Aug as Unit 2 · B
  v_last_day date := '2026-08-31';
  v_first_day date := '2026-09-01';
  v_unit     smallint;
  v_stragglers text;
begin
  select id into v_petrol from public.tanks where fuel_type = 'petrol';
  select id into v_diesel from public.tanks where fuel_type = 'diesel';

  if v_petrol is null or v_diesel is null then
    raise exception '061: expected one petrol tank and one diesel tank.';
  end if;

  -- Already done, on a project this has been applied to before.
  if exists (select 1 from public.nozzles
              where id in (v_old_a, v_old_b) and retired_on is not null) then
    raise notice '061: Unit 1''s petrol nozzles are already retired - nothing to do.';
    return;
  end if;

  -- Nothing to do on a project that never had these rows (a fresh restore, or
  -- the offline build's own database).
  if not exists (select 1 from public.nozzles where id in (v_old_a, v_old_b)) then
    raise notice '061: those nozzles are not in this database - nothing to do.';
    return;
  end if;

  select unit_number into v_unit from public.nozzles where id = v_old_a;

  -- The same check `replace_unit()` makes, and for the same reason: retiring a
  -- nozzle on a day it has readings past would strand them outside their own
  -- service window - still in the books and in the tank's stock, but on days
  -- the sheet would refuse to open.
  select string_agg(distinct to_char(nr.reading_date, 'FMDD Mon YYYY'), ', ')
    into v_stragglers
    from public.nozzle_readings nr
   where nr.nozzle_id in (v_old_a, v_old_b)
     and nr.reading_date > v_last_day;

  if v_stragglers is not null then
    raise exception
      '061: Unit % already has readings after % (%). Clear those days before running this, or '
      'the repair would strand them outside the pump''s service window.',
      v_unit, to_char(v_last_day, 'FMDD Mon YYYY'), v_stragglers;
  end if;

  -- 1 + 2. Back onto petrol, and stopped on their last petrol day. One
  -- statement: `nozzles_retired_is_not_active` will not have retired_on and
  -- is_active disagree even for an instant.
  update public.nozzles
     set tank_id    = v_petrol,
         retired_on = v_last_day,
         is_active  = false
   where id in (v_old_a, v_old_b);

  -- 3. The same pump again, on diesel, from the day it changed over - with the
  -- meter where it actually stood, read off its own last petrol day.
  insert into public.nozzles
    (tank_id, unit_number, nozzle_label, starting_reading, commissioned_on, is_active)
  select v_diesel, old.unit_number, old.nozzle_label, last_reading.closing_reading,
         v_first_day, true
    from public.nozzles old
    join lateral (
      select nr.closing_reading
        from public.nozzle_readings nr
       where nr.nozzle_id = old.id
       order by nr.reading_date desc
       limit 1
    ) last_reading on true
   where old.id in (v_old_a, v_old_b);

  -- 4. Lineage, the same way replace_unit() draws it.
  update public.nozzles old
     set replaced_by = new_n.id
    from public.nozzles new_n
   where old.id in (v_old_a, v_old_b)
     and new_n.unit_number     = old.unit_number
     and new_n.commissioned_on = v_first_day
     and new_n.nozzle_label    = old.nozzle_label;

  raise notice '061: Unit % is petrol to %, diesel from %.',
    v_unit, to_char(v_last_day, 'FMDD Mon YYYY'), to_char(v_first_day, 'FMDD Mon YYYY');
end;
$$;

-- The tanks' cached book stock is recomputed from the readings by trigger, and
-- no reading was touched here - but the nozzles those readings hang off did
-- move between tanks, so both cached figures are refreshed by hand.
select public.recalc_tank_stock(id) from public.tanks;

-- ===================================================================== 062_august_keeps_the_numbers_august_had.sql
-- =============================================================================
-- 062_august_keeps_the_numbers_august_had.sql
--
-- August's unit numbers go back to the forecourt August actually had.
--
-- WHY THIS WAS NOT POSSIBLE BEFORE 061, AND IS NOW. `unit_number` is one field
-- per nozzle row, so a rename applies to every day that row has ever traded -
-- which 058 chose deliberately, and which was the only behaviour available
-- while a pump that moved was a single row spanning both months. The petrol
-- pump renumbered 2 -> 1 on 1 Sep therefore took its whole August with it, and
-- the scrapped diesel pump renumbered 1 -> 2 took its whole August the other
-- way. August ended up captioned as the mirror image of the forecourt that
-- actually stood there:
--
--                     the books said        the forecourt in August
--     Unit 1            petrol                 diesel  (the scrapped pump)
--     Unit 2            diesel                 petrol  (the pump that moved)
--
-- 061 split the pump that moved into two rows - petrol to 31 Aug, diesel from
-- 1 Sep - because its FUEL changed on a date. Its POSITION changed on the same
-- date, and now that there are two rows there is somewhere to put the two
-- answers. So the fix is only a relabelling of rows that already have the right
-- dates on them:
--
--   * the scrapped diesel pump's rows go back to Unit 1, which is where it
--     stood every day it ever dispensed;
--   * the moved pump's AUGUST rows go back to Unit 2, which is where it stood
--     every day those readings were taken.
--
-- September's rows are not touched. Unit 1 is diesel and Unit 2 is petrol from
-- 1 September, which is the forecourt today.
--
-- ONE STATEMENT, BECAUSE IT IS A SWAP. Two rows pass through claiming Unit 1
-- on days that overlap nothing, but `nozzles_one_pump_per_position` is checked
-- per statement unless it is deferred - which it is (058), and the whole
-- relabel therefore lives inside one DO block so the check happens once, when
-- the forecourt is whole again.
--
-- THE SCRAPPED PUMP'S SUCCESSOR ALSO HAS TO MOVE. It currently points at the
-- new PETROL pump, which was true only in the sense that both wore the number
-- 2 for a day: the owner ran "Replace this unit" on Unit 2 at a moment when the
-- renumbering had already happened. Nothing about the machines matched. What
-- actually took over the scrapped pump's position AND its fuel is the pump
-- standing at Unit 1 on diesel today, so that is where the link goes.
--
-- That leaves the September diesel row with two predecessors, and both are
-- true: it is the same machine as the August Unit 2 petrol row (it moved), and
-- it is the successor at position 1 to the August Unit 1 diesel row (it took
-- over). `replaced_by` is a record, read by nothing in the app - a fan-in costs
-- nothing and saying only one of the two would be the lie.
--
-- NO READING, NO RUPEE AND NO LITRE MOVES. `unit_number` is a caption. Which
-- tank a sale came out of is `tank_id`, which 061 already put right, and the
-- money lives on the readings themselves.
--
-- Safe to run twice: if the scrapped pump is already back at Unit 1 it does
-- nothing.
-- =============================================================================

do $$
declare
  v_diesel  uuid;
  v_scrap_a uuid := '2f317993-6ec5-4271-8ae8-c83cbbaed8eb';  -- scrapped diesel pump, A
  v_scrap_b uuid := '5d1d838a-c597-4e83-aee9-f30b029b25ed';  -- scrapped diesel pump, B
  v_moved_a uuid := '7c4bd261-a5a8-4f0b-b5eb-dcf24a86d6ae';  -- the pump that moved, August
  v_moved_b uuid := '078e541c-6f53-430a-9047-72ad12a5e24f';
begin
  select id into v_diesel from public.tanks where fuel_type = 'diesel';

  if not exists (select 1 from public.nozzles where id in (v_scrap_a, v_scrap_b)) then
    raise notice '062: those nozzles are not in this database - nothing to do.';
    return;
  end if;

  if (select unit_number from public.nozzles where id = v_scrap_a) = 1 then
    raise notice '062: August already carries August''s numbers - nothing to do.';
    return;
  end if;

  -- 061 is what makes this a relabel rather than a rewrite of history. Without
  -- it the moved pump is still one row and there is no August to number
  -- separately.
  if exists (select 1 from public.nozzles
              where id in (v_moved_a, v_moved_b) and retired_on is null) then
    raise exception
      '062: the pump that moved has not been split at 31 Aug yet. Apply 061 first.';
  end if;

  update public.nozzles set unit_number = 1 where id in (v_scrap_a, v_scrap_b);
  update public.nozzles set unit_number = 2 where id in (v_moved_a, v_moved_b);

  update public.nozzles old
     set replaced_by = successor.id
    from public.nozzles successor
   where old.id in (v_scrap_a, v_scrap_b)
     and successor.unit_number     = 1
     and successor.commissioned_on = '2026-09-01'
     and successor.tank_id         = v_diesel
     and successor.nozzle_label    = old.nozzle_label;

  raise notice '062: August reads Unit 1 diesel, Unit 2 petrol again.';
end;
$$;

-- ===================================================================== 063_correcting_a_ledger_entry.sql
-- =============================================================================
-- 063_correcting_a_ledger_entry.sql
--
-- An "edit" button for the customer ledger, in a ledger that cannot be edited.
--
-- THE RULE THIS HAS TO LIVE INSIDE. `ledger_entries` is append-only and always
-- has been: two triggers refuse UPDATE and DELETE outright (002), and RLS grants
-- select and insert and nothing else (003). That is not caution, it is the point
-- of the table - a customer's balance is the sum of rows nobody can quietly
-- reach back and change, which is the whole reason the owner can trust it
-- against a paper khata that anyone could have rubbed out.
--
-- So the button cannot edit. What the owner actually means when he says "I
-- typed 6,000 and he paid 600" is: cancel what I wrote, and put the right thing
-- in its place. That is two new rows, and the page has said so in words since
-- the beginning - "a mistake is corrected with a new entry pointing the other
-- way, so the history always adds up". This migration is that sentence made
-- into a button.
--
-- WHAT A CORRECTION IS, EXACTLY.
--
--   * a REVERSAL - same amount, same date, opposite direction - which cancels
--     the wrong row where it stands, so every balance from that date onward is
--     right again rather than only the balance today;
--   * and, unless the entry should never have existed at all, a REPLACEMENT
--     carrying what it should have said.
--
-- Both in one statement. Half a correction is worse than none: a reversal
-- without its replacement silently wipes a real payment, and a replacement
-- without its reversal doubles it. Neither is visible on any screen afterwards.
--
-- WHY A COLUMN AND NOT JUST TWO MORE ROWS. Without `corrects_entry_id` the
-- ledger grows three rows of the same amount and nothing says which cancels
-- which. The owner reading down the page cannot tell a real payment from a
-- reversed one, which is a worse account than he had before the button existed.
-- The column lets the table strike the row that was cancelled, mark the row
-- that cancelled it, and refuse to cancel the same row twice.
--
-- WHAT CANNOT BE CORRECTED HERE, AND WHY.
--
--   * A row posted automatically from a sale - `credit_sale_id` (a nozzle
--     reading) or `lubricant_sale_id` (a counter sale of oil). The mistake is in
--     the SALE - the litres, the rate, the customer - and cancelling only its
--     ledger side would leave the sale and the ledger disagreeing about the same
--     money forever. 016 already reverses the slip when the reading is deleted,
--     so the sale is where that is fixed, and the error says which screen.
--   * A reversal. It exists only to cancel something else and has no meaning of
--     its own; if the correction was wrong, the REPLACEMENT is the row to
--     correct, and it is an ordinary entry.
--   * A row already corrected. One cancellation per entry, enforced by a unique
--     index rather than by the function, so it holds however the row is written.
--
-- OWNER ONLY. Recording a payment is a data-entry job; deciding that something
-- already in the books was wrong is not. This matches `recordLedgerAdjustment`,
-- which is owner-only for the same reason.
-- =============================================================================

alter table public.ledger_entries
  add column if not exists corrects_entry_id uuid references public.ledger_entries(id);

comment on column public.ledger_entries.corrects_entry_id is
  'Set on a reversal row: the entry it cancels. Null on every ordinary entry. The ledger stays append-only - this records WHY a row is there, it does not permit editing the row it points at.';

-- One cancellation per entry. Without this, two reversals of the same row would
-- both post and take the balance the wrong way by the amount twice.
create unique index if not exists ledger_entries_one_correction_per_entry
  on public.ledger_entries (corrects_entry_id)
  where corrects_entry_id is not null;

alter table public.ledger_entries drop constraint if exists ledger_entries_no_self_correction;
alter table public.ledger_entries
  add constraint ledger_entries_no_self_correction
  check (corrects_entry_id is null or corrects_entry_id <> id);

-- ---------------------------------------------------------------------------
-- The correction itself.
--
-- One function, because the reversal and the replacement have to arrive
-- together or not at all - see above. It returns what it wrote so the action
-- can say "Rs 6,000 cancelled, Rs 600 recorded" rather than "Saved".
--
-- p_amount / p_entry_date / p_note describe the REPLACEMENT. p_remove says the
-- entry should not exist at all, and then the three are ignored.
-- ---------------------------------------------------------------------------
create or replace function public.correct_ledger_entry(
  p_entry_id   uuid,
  p_remove     boolean default false,
  p_amount     numeric default null,
  p_entry_date date    default null,
  p_note       text    default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old        public.ledger_entries;
  v_reversal   uuid;
  v_replacement uuid;
  v_amount     numeric;
begin
  if not public.is_super_admin() then
    raise exception 'Only the owner may correct a ledger entry' using errcode = '42501';
  end if;

  select * into v_old from public.ledger_entries where id = p_entry_id;

  if v_old.id is null then
    raise exception 'That entry is no longer on the ledger.' using errcode = '23503';
  end if;

  if v_old.credit_sale_id is not null or v_old.lubricant_sale_id is not null then
    raise exception
      'This entry was posted automatically from a %, so it cannot be corrected here - the sale '
      'and the ledger have to keep saying the same thing about the same money. Correct the sale '
      'itself and the slip follows it.',
      case when v_old.credit_sale_id is not null then 'nozzle reading' else 'lubricant sale' end
      using errcode = '23514';
  end if;

  if v_old.corrects_entry_id is not null then
    raise exception
      'This row was posted to cancel an earlier entry, so there is nothing in it to correct. If '
      'the correction itself was wrong, correct the replacement entry instead.'
      using errcode = '23514';
  end if;

  if exists (select 1 from public.ledger_entries where corrects_entry_id = p_entry_id) then
    raise exception
      'This entry has already been cancelled once. Correct the entry that replaced it instead.'
      using errcode = '23505';
  end if;

  if not p_remove then
    if p_amount is null or round(p_amount) <= 0 then
      raise exception 'Enter what the entry should have been, in whole rupees above zero.'
        using errcode = '23514';
    end if;
    if p_entry_date is null then
      raise exception 'Enter the date the entry should carry.' using errcode = '23514';
    end if;
  end if;

  -- THE REVERSAL. Same amount, same date, opposite direction - so the balance
  -- is right on every day from the mistake onward, not merely today.
  insert into public.ledger_entries
    (customer_id, entry_type, amount, entry_date, note, created_by, corrects_entry_id)
  values (
    v_old.customer_id,
    (case when v_old.entry_type = 'debit' then 'credit' else 'debit' end)::public.ledger_entry_type,
    v_old.amount,
    v_old.entry_date,
    'Cancels: ' || coalesce(nullif(btrim(v_old.note), ''),
                            case when v_old.entry_type = 'debit' then 'an entry' else 'a payment' end),
    auth.uid(),
    v_old.id
  )
  returning id into v_reversal;

  if not p_remove then
    v_amount := round(p_amount);

    insert into public.ledger_entries
      (customer_id, entry_type, amount, entry_date, note, created_by)
    values (
      v_old.customer_id,
      v_old.entry_type,
      v_amount,
      p_entry_date,
      coalesce(nullif(btrim(p_note), ''), v_old.note),
      auth.uid()
    )
    returning id into v_replacement;
  end if;

  return jsonb_build_object(
    'customer_id',    v_old.customer_id,
    'entry_type',     v_old.entry_type,
    'was_amount',     v_old.amount,
    'now_amount',     v_amount,
    'removed',        p_remove,
    'reversal_id',    v_reversal,
    'replacement_id', v_replacement
  );
end;
$$;

comment on function public.correct_ledger_entry(uuid, boolean, numeric, date, text) is
  'Cancels a hand-entered ledger row and, unless removing it, posts what it should have said - both in one statement. Owner only. The ledger stays append-only.';

revoke execute on function public.correct_ledger_entry(uuid, boolean, numeric, date, text) from public, anon;
grant  execute on function public.correct_ledger_entry(uuid, boolean, numeric, date, text) to authenticated;

-- ===================================================================== 064_the_ledger_carries_its_own_balance.sql
-- =============================================================================
-- 064_the_ledger_carries_its_own_balance.sql
--
-- Every ledger row learns what was owed immediately after it, so that the screen
-- and the printed statement can both show it and cannot disagree.
--
-- Two functions, one window. `get_ledger_entries_page` is the customer page's
-- paged table; `get_ledger_entries_for_statement` is the whole account, for the
-- statement of account, which since this round lists every fill and every payment
-- with the balance standing after each one rather than only the unpaid fills.
--
-- The first half of the story is a bug the pager introduced.
--
-- The Balance column on the customer page was counting from zero on every page.
--
-- WHAT WENT WRONG. `CustomerLedgerTable` was written when the customer page
-- listed the WHOLE ledger: it sorted the rows oldest first, ran a total through
-- them starting at zero, and printed it against each row - "what was owed
-- immediately after this entry", which is how a paper khata reads and was
-- exactly right at the time. Then the ledger got a pager (25 rows a page), and
-- the same loop kept running - now over a page. Starting at zero is only true
-- for the first entry the customer ever had, and that row is on the LAST page.
--
-- So every figure in the column was out by the net of everything older than the
-- page, and page 1 - the page anybody actually looks at - was out by the most.
-- A real customer owing Rs 97,515 had Rs -59,728 printed against his newest
-- entry: not merely the wrong number, the wrong SIGN, a page saying the pump
-- owed HIM sixty thousand rupees. He was also carrying a run of big payments
-- inside the newest 25 rows, which is what made the page-local total negative;
-- a customer whose recent page is mostly fills gets a figure that is merely too
-- small, which is worse, because nothing about it looks wrong.
--
-- The balance card above the table and the printed statement were both right
-- throughout - they are summed in Postgres over every row (`customer_balance`,
-- and the allocation in customer-statement.js, which reads the whole ledger on
-- purpose). Only the column you would use to CHECK them was wrong, which is the
-- particular kind of bug this app cannot afford: the owner reads the statement,
-- turns to the history to see where a figure came from, and the history
-- disagrees with it. After that he does not trust either one.
--
-- WHY THE FIX IS A WINDOW FUNCTION AND NOT A BIGGER FETCH. The obvious repair -
-- fetch the whole ledger again and slice it in JavaScript - throws away the
-- reason the table is paged and puts a money figure back in a double. A running
-- balance is a money figure: it is `customer_balance()` stopped part way, and
-- the two must agree to the paisa on the last row or the column is lying again
-- in a quieter way. Postgres already sums this exactly, in `numeric`, so it sums
-- it here too and the page carries the answer with it.
--
--   sum(...) over (order by entry_date, created_at, id)
--
-- is computed over EVERY row for the customer and the page is taken after, so
-- the figure against a row is the same whichever page that row happens to fall
-- on - which is the property the old code could not have.
--
-- THE ORDER IS THE SAME TRIPLE THE STATEMENT USES - `entry_date`, then
-- `created_at`, then `id`. The date is the business day and is what the customer
-- recognises; `created_at` breaks a tie within a day in the order the rows were
-- written; `id` is there because a correction (063) writes its reversal and its
-- replacement in ONE statement, so both carry the identical `created_at` and
-- date-plus-time alone is not a total order. Without a final tiebreak Postgres
-- may hand back those two rows in either order on either query, so the running
-- total and the list could be walking the ledger in different orders - and the
-- column would disagree with itself between one page load and the next. The
-- pair nets to zero either way; what matters is that it is decided, and decided
-- the same way `oldestFirst` in customer-statement.js decides it.
--
-- ONE ROUND TRIP, THREE ANSWERS. The rows, the count for the pager, and the ids
-- of the entries that have been cancelled - which the table needs for the whole
-- customer, not just the page, because `corrects_entry_id` points FORWARD and an
-- August mistake corrected in September has its two halves on different pages.
-- That was already a second query; it is now part of the same one.
-- =============================================================================

create or replace function public.get_ledger_entries_page(
  p_customer_id uuid,
  p_limit       integer default 25,
  p_offset      integer default 0
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  -- A hand-typed page size cannot ask for the whole book, and cannot ask for
  -- nothing either; the pager only ever sends 25.
  v_limit  integer := least(greatest(coalesce(p_limit, 25), 1), 200);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_result jsonb;
begin
  -- Same gate as get_customer_statement: staff need one customer's ledger to
  -- record a payment against it. It exposes one customer, never the whole book.
  if not public.is_active_staff() then
    raise exception 'Not authorised' using errcode = '42501';
  end if;

  with running as (
    select le.*,
           sum(case when le.entry_type = 'debit' then le.amount else -le.amount end)
             over (order by le.entry_date, le.created_at, le.id
                   rows between unbounded preceding and current row) as balance_after
      from public.ledger_entries le
     where le.customer_id = p_customer_id
  ),
  page as (
    select r.*
      from running r
     order by r.entry_date desc, r.created_at desc, r.id desc
     limit v_limit offset v_offset
  )
  select jsonb_build_object(
    -- Newest first, the way the table reads, and ordered inside the aggregate
    -- so the array arrives in that order rather than in whatever order the
    -- rows came out of the subquery.
    'rows', coalesce(
      (select jsonb_agg(to_jsonb(p) order by p.entry_date desc, p.created_at desc, p.id desc)
         from page p),
      '[]'::jsonb),
    'total', (select count(*) from running),
    'corrected_ids', coalesce(
      (select jsonb_agg(r.corrects_entry_id)
         from running r
        where r.corrects_entry_id is not null),
      '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$$;

comment on function public.get_ledger_entries_page(uuid, integer, integer) is
  'One page of a customer''s ledger, newest first, each row carrying the balance after it - summed in Postgres over the WHOLE ledger, so the figure does not depend on which page the row falls on. Also returns the row count for the pager and the ids of every cancelled entry.';

revoke execute on function public.get_ledger_entries_page(uuid, integer, integer) from public, anon;
grant  execute on function public.get_ledger_entries_page(uuid, integer, integer) to authenticated;

-- ---------------------------------------------------------------------------
-- The whole account, oldest first, for the statement.
--
-- THE DELIBERATE OPPOSITE OF THE PAGED FUNCTION ABOVE, and for a reason worth
-- writing down: that one pages because the screen only ever LISTS rows. The
-- statement IS the account - every fill, every payment, the balance after each -
-- so a page of 25 would print a document that stops in the middle of August with
-- no line saying it had.
--
-- ONE JSON VALUE RATHER THAN A ROW SET, which also settles a limit the app used
-- to work around in JavaScript: PostgREST caps a table read at 1,000 rows by
-- default and hands back the first 1,000 without complaining, so the fetch this
-- replaces looped in batches to be sure it had them all. A regular haulier runs
-- to a few hundred entries a year, so the cap was years away and not never - and
-- the failure it produces is a statement that looks entirely normal and asks for
-- the wrong money. A jsonb return has no such cap.
--
-- No `limit` here on purpose. The caller wants the account or it wants nothing;
-- a truncated statement is the one outcome worse than a slow one.
-- ---------------------------------------------------------------------------

create or replace function public.get_ledger_entries_for_statement(p_customer_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_result jsonb;
begin
  if not public.is_active_staff() then
    raise exception 'Not authorised' using errcode = '42501';
  end if;

  select coalesce(jsonb_agg(to_jsonb(r) order by r.entry_date, r.created_at, r.id), '[]'::jsonb)
    into v_result
    from (
      select le.*,
             sum(case when le.entry_type = 'debit' then le.amount else -le.amount end)
               over (order by le.entry_date, le.created_at, le.id
                     rows between unbounded preceding and current row) as balance_after
        from public.ledger_entries le
       where le.customer_id = p_customer_id
    ) r;

  return v_result;
end;
$$;

comment on function public.get_ledger_entries_for_statement(uuid) is
  'A customer''s whole ledger, oldest first, each row carrying the balance after it. For the printed statement of account, which lists every movement rather than a page of them.';

revoke execute on function public.get_ledger_entries_for_statement(uuid) from public, anon;
grant  execute on function public.get_ledger_entries_for_statement(uuid) to authenticated;

-- ===================================================================== 065_a_main_bank_account.sql
-- =============================================================================
-- 065_a_main_bank_account.sql
--
-- One bank account can be marked as the MAIN one, and the money in / money out
-- form on Banking starts on it.
--
-- WHY. The form used to start on whichever account was added first, which is
-- the order `getBankAccounts()` reads them in. On this pump that is not the
-- account the day's cash goes into, so every deposit began with changing the
-- account - the owner asked for the main account to be the default. Nothing in
-- the books recorded which account that is, so it is recorded here, and the
-- owner marks it himself on Banking ("Make main"). Guessing it (the busiest
-- account, the last one used) was offered and turned down: he knows which
-- account is his main one, and a guess would be wrong the month another
-- account happened to be busier.
--
-- NOTHING ALREADY IN THE BOOKS CHANGES. A new column, false/empty on every
-- existing account until one is marked; no balance, total or transaction is
-- touched.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- The flag.
--
-- NULLABLE ON PURPOSE, with null read as "not main". `restore_everything()`
-- (migration 051) writes every column of a table BY NAME from the backup file,
-- and a backup taken before this migration has no `is_main` in its rows, so the
-- value arrives as null. NOT NULL would refuse every account in such a file and
-- with it the whole restore - a backup that cannot be put back is worse than no
-- flag at all. A null restores as "not main", which is exactly what it was.
-- ---------------------------------------------------------------------------
alter table public.bank_accounts
  add column if not exists is_main boolean default false;

comment on column public.bank_accounts.is_main is
  'The account the Banking form starts on. At most one is true; null and false both mean not main.';

-- At most one main account. A partial unique index on a constant: every row it
-- covers has the same key, so a second `true` is refused by the database, not
-- merely avoided by the app.
create unique index if not exists bank_accounts_one_main
  on public.bank_accounts ((true))
  where is_main;

-- ---------------------------------------------------------------------------
-- The list the app reads carries it.
--
-- Recreated with `is_main` as the LAST column: CREATE OR REPLACE VIEW may only
-- add columns at the end, and the month-export functions (019, 025, 030, 040)
-- read this view by column name, so nothing they use moves. Same body as 018
-- otherwise, security_invoker kept, so the owner-only policy on the table still
-- decides who sees a row.
-- ---------------------------------------------------------------------------
create or replace view public.bank_account_balances
with (security_invoker = true) as
select a.id,
       a.bank_name,
       a.account_label,
       a.account_number,
       a.opening_balance,
       a.pruned_count,
       a.created_at,
       a.pruned_deposits
         + coalesce(sum(t.amount) filter (where t.txn_type = 'deposit'), 0) as total_deposited,
       a.pruned_payments
         + coalesce(sum(t.amount) filter (where t.txn_type = 'payment'), 0) as total_paid,
       a.opening_balance
         + a.pruned_deposits - a.pruned_payments
         + coalesce(sum(t.amount) filter (where t.txn_type = 'deposit'), 0)
         - coalesce(sum(t.amount) filter (where t.txn_type = 'payment'), 0) as balance,
       count(t.id) as kept_count,
       coalesce(a.is_main, false) as is_main
  from public.bank_accounts a
  left join public.bank_transactions t on t.account_id = a.id
 group by a.id;

comment on view public.bank_account_balances is
  'Each account with its balance and lifetime totals. Includes what the '
  '60-entry cap removed, so the figures do not change when old detail ages out. '
  'is_main (065) says which account the Banking form starts on.';

grant select on public.bank_account_balances to authenticated;

-- ---------------------------------------------------------------------------
-- Marking an account as the main one.
--
-- TWO STATEMENTS, AND THEIR ORDER IS THE POINT. A unique index is checked row
-- by row as an UPDATE runs, so one statement that turned the new account on
-- and the old one off could meet the new `true` before the old one was
-- cleared, and be refused depending on which row Postgres happened to visit
-- first. Clearing first and setting second, inside one function (so one
-- transaction), can never have two at once - and a failure part-way leaves no
-- main account rather than two.
--
-- Owner only, like everything on bank_accounts (018). Marking the account that
-- is already main is not an error; it changes nothing.
-- ---------------------------------------------------------------------------
create or replace function public.set_main_bank_account(p_account_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_super_admin() then
    raise exception 'Only the owner can choose the main bank account.'
      using errcode = '42501';
  end if;

  if not exists (select 1 from public.bank_accounts where id = p_account_id) then
    raise exception 'That account is not on the list any more. Reload the page and choose again.'
      using errcode = 'P0002';
  end if;

  update public.bank_accounts
     set is_main = false
   where is_main
     and id <> p_account_id;

  update public.bank_accounts
     set is_main = true
   where id = p_account_id
     and is_main is not true;
end;
$$;

comment on function public.set_main_bank_account(uuid) is
  'Makes one bank account the main one (the Banking form starts on it), clearing whichever was main before.';

revoke execute on function public.set_main_bank_account(uuid) from public, anon;
grant  execute on function public.set_main_bank_account(uuid) to authenticated;

-- ===================================================================== 066_a_backdated_price_reprices_its_days.sql
-- =============================================================================
-- 066_a_backdated_price_reprices_its_days.sql
--
-- A price set for a day that already has readings now re-prices those readings.
--
-- THE BUG, AS THE OWNER FOUND IT. Readings, 27 Sep 2026, Unit 1 Nozzle A:
-- 236.20 L, and Settings says diesel was Rs 412.25 that day. 236.20 x 412.25 is
-- Rs 97,373.45; the nozzle said Rs 98,221. The difference is the RATE: the
-- reading was saved at 09:16 with Rs 415.84, the rate in force since 25 Sep,
-- and the 412.25 for 26 and 27 Sep was added at 10:01, forty-five minutes
-- later. Every reading carries a copy of its rate (`rate_per_litre`), so the new
-- price never reached it. Both days, both fuels: twelve readings, Rs 3,560.41
-- short on the books.
--
-- NOT A ONE-OFF. The same order of events - readings first, the morning's new
-- price second - had already happened on 14 Aug, 25 Aug and 12 Sep. The
-- owner enters the day's price when he gets to it, and nothing on either screen
-- said the two had crossed.
--
-- WHY THE COPY EXISTS, AND WHY IT STAYS. A rate on the reading row is what
-- stops a price change quietly rewriting last week's takings: a new price set
-- from TODAY must not touch anything already sold. That is still true, and
-- still how it works - a price effective from today, or from any date with no
-- readings yet, changes nothing here.
--
-- WHAT CHANGES. A price effective from a PAST date is the owner saying, in so
-- many words, "from that day, this was the price." Readings already saved in
-- the span that price now governs were sold at it. So setting it re-prices
-- them, and says so in the answer it gives back ("4 readings on 26-27 Sep
-- re-priced from Rs 415.84"). Not quietly: the Settings form says it before
-- saving, and the result says what moved.
--
-- THE SPAN IS BOUNDED. A price covers [its effective_from, the next price's
-- effective_from). Only readings of that fuel inside that span, whose rate is
-- not already the rate now in force for their day, are touched. A reading on a
-- later day belongs to a later price and is left alone - including the older
-- days (14 Aug, 25 Aug, 12 Sep) that disagree with the price table today:
-- putting those right is the owner's call, day by day, not a side effect of
-- setting an unrelated price.
--
-- REMOVING A PRICE is the same thing the other way. The days that price
-- covered fall back to the price before it, so their readings are re-priced to
-- that - or, if no earlier price exists, left alone and reported, because a
-- reading needs some rate and inventing one is not this function's job.
--
-- WHAT A RE-PRICE WRITES. `rate_per_litre` and `cash_amount`, in one UPDATE.
-- `sale_amount` is generated; credit is the slips' total and does not move; the
-- cash is derived exactly the way 052 derives it on insert, so the split
-- constraint (cash + credit = litres x rate) holds by construction. If the
-- slips come to more than the re-priced sale, that is refused with a sentence
-- naming the day and the nozzle, and nothing is saved - price included.
--
-- AUDIT. Each re-priced reading is an UPDATE, so `trg_write_activity` logs it
-- with the before and after values. Nothing is re-priced that the log does not
-- see.
--
-- Owner only (is_super_admin), security definer like clear_day (014), because
-- a price change is the owner's and the readings it re-prices may have been
-- entered by staff.
--
-- Nothing here adds a column, so the backup (051) needs nothing new.
-- =============================================================================

create or replace function public.reprice_readings_for_span(
  p_fuel_type public.fuel_type,
  p_from      date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_until        date;
  v_count        int;
  v_first        date;
  v_last         date;
  v_old_rates    text;
  v_new_rate     numeric;
  v_before       numeric(14, 2);
  v_after        numeric(14, 2);
  v_short        record;
  v_unpriced     int;
begin
  if not public.is_super_admin() then
    raise exception 'Only the owner may change a fuel price' using errcode = '42501';
  end if;

  -- The span this date's price governs: up to, not including, the next price.
  select min(fp.effective_from) into v_until
    from public.fuel_prices fp
   where fp.fuel_type = p_fuel_type and fp.effective_from > p_from;

  -- Readings in the span with no price at all to fall back to (a price removed
  -- with nothing before it). Left as they are and counted.
  select count(*) into v_unpriced
    from public.nozzle_readings r
    join public.nozzles n on n.id = r.nozzle_id
    join public.tanks t on t.id = n.tank_id
   where t.fuel_type = p_fuel_type
     and r.reading_date >= p_from
     and (v_until is null or r.reading_date < v_until)
     and public.current_fuel_rate(p_fuel_type, r.reading_date) is null;

  -- The re-price would leave a nozzle's credit slips larger than its sale.
  -- Refused here, with a sentence, rather than by the check constraint.
  select r.reading_date, n.unit_number, n.nozzle_label, r.credit_amount,
         round((r.closing_reading - r.opening_reading)
               * public.current_fuel_rate(p_fuel_type, r.reading_date), 2) as new_sale
    into v_short
    from public.nozzle_readings r
    join public.nozzles n on n.id = r.nozzle_id
    join public.tanks t on t.id = n.tank_id
   where t.fuel_type = p_fuel_type
     and r.reading_date >= p_from
     and (v_until is null or r.reading_date < v_until)
     and public.current_fuel_rate(p_fuel_type, r.reading_date) is not null
     and r.rate_per_litre <> public.current_fuel_rate(p_fuel_type, r.reading_date)
     and r.credit_amount > round((r.closing_reading - r.opening_reading)
                                 * public.current_fuel_rate(p_fuel_type, r.reading_date), 2)
   order by r.reading_date
   limit 1;

  if found then
    raise exception
      'At the new rate, Unit % Nozzle % on % sold Rs %, but its credit slips come to Rs %. '
      'Correct the slips on that day first, then set the rate again.',
      v_short.unit_number, v_short.nozzle_label, to_char(v_short.reading_date, 'DD Mon YYYY'),
      to_char(v_short.new_sale, 'FM999,999,999,990.00'),
      to_char(v_short.credit_amount, 'FM999,999,999,990.00')
      using errcode = '23514';
  end if;

  -- What is about to move, for the answer. Read before the update.
  select count(*), min(r.reading_date), max(r.reading_date),
         string_agg(distinct to_char(r.rate_per_litre, 'FM999,990.00'), ', '),
         sum(r.sale_amount),
         sum(round((r.closing_reading - r.opening_reading)
                   * public.current_fuel_rate(p_fuel_type, r.reading_date), 2))
    into v_count, v_first, v_last, v_old_rates, v_before, v_after
    from public.nozzle_readings r
    join public.nozzles n on n.id = r.nozzle_id
    join public.tanks t on t.id = n.tank_id
   where t.fuel_type = p_fuel_type
     and r.reading_date >= p_from
     and (v_until is null or r.reading_date < v_until)
     and public.current_fuel_rate(p_fuel_type, r.reading_date) is not null
     and r.rate_per_litre <> public.current_fuel_rate(p_fuel_type, r.reading_date);

  v_new_rate := public.current_fuel_rate(p_fuel_type, p_from);

  -- The same derivation as create_nozzle_reading (052): the sale is exactly
  -- the generated column's expression, the cash is exactly sale - credit.
  update public.nozzle_readings r
     set rate_per_litre = public.current_fuel_rate(p_fuel_type, r.reading_date),
         cash_amount    = round((r.closing_reading - r.opening_reading)
                                * public.current_fuel_rate(p_fuel_type, r.reading_date), 2)
                          - r.credit_amount
    from public.nozzles n
    join public.tanks t on t.id = n.tank_id
   where n.id = r.nozzle_id
     and t.fuel_type = p_fuel_type
     and r.reading_date >= p_from
     and (v_until is null or r.reading_date < v_until)
     and public.current_fuel_rate(p_fuel_type, r.reading_date) is not null
     and r.rate_per_litre <> public.current_fuel_rate(p_fuel_type, r.reading_date);

  return jsonb_build_object(
    'fuel_type',  p_fuel_type,
    'repriced',   coalesce(v_count, 0),
    'first_day',  v_first,
    'last_day',   v_last,
    'old_rates',  v_old_rates,
    'new_rate',   v_new_rate,
    'before',     coalesce(v_before, 0),
    'after',      coalesce(v_after, 0),
    'unpriced',   v_unpriced
  );
end;
$$;

comment on function public.reprice_readings_for_span(public.fuel_type, date) is
  'Brings the readings of one fuel, in the span the price dated p_from governs, '
  'onto the rate now in force for each day. Owner only. See 066.';

revoke execute on function public.reprice_readings_for_span(public.fuel_type, date) from public, anon;
grant execute on function public.reprice_readings_for_span(public.fuel_type, date) to authenticated;


